use serde::{Deserialize, Serialize};

/// Lifecycle state machine for policy rules generated or managed by the meta-level triage
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum RuleLifecycleState {
    #[default]
    Draft,
    Probationary,
    Graduated,
    Quarantined,
}

impl std::fmt::Display for RuleLifecycleState {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Draft => write!(f, "draft"),
            Self::Probationary => write!(f, "probationary"),
            Self::Graduated => write!(f, "graduated"),
            Self::Quarantined => write!(f, "quarantined"),
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TriageRequest {
    pub triage_id: String,
    pub action_id: String,
    pub trace_id: String,
    pub tenant_id: String,
    pub caller_did: String,
    pub tool_name: String,
    pub operation_kind: String,
    pub arguments: serde_json::Value,
    #[serde(default)]
    pub skill_manifest: Option<serde_json::Value>,
    #[serde(default)]
    pub call_chain_context: Option<serde_json::Value>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TriageRecommendation {
    RecommendApprove,
    RequireHumanApproval,
    RecommendReject,
}

/// Plane A: Verifiable Deterministic Metrics (TCB Grounding)
/// Computed deterministically from tool contracts, OpenAPI/manifest specs, and typed payload extraction.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct DeterministicMetrics {
    pub schema_verified: bool,
    pub is_mutation: bool,
    pub operation_kind: String,
    pub financial_exposure_cents: u64,
    pub financial_indeterminate: bool,
    pub touched_iam_scopes: Vec<String>,
    pub reversibility: String,
    pub is_idempotent: bool,
    pub projected_fields: Vec<String>,
    pub risk_classification: String, // "Low", "Medium", "High", "Critical"
}

/// Plane B: Cognitive Advisory Context (Strictly Non-TCB)
/// Cognitive semantic contextualization from Swarm Gateway. Explicitly marked as untrusted advisory.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct CognitiveAdvisory {
    pub intent_summary: String,
    pub risk_factors: Vec<String>,
    pub mitigation_notes: String,
    pub advisory_notice: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct BlastRadius {
    pub data_classification: String,
    pub financial_exposure_cents: u64,
    pub reversibility: String,
    pub risk_level: String, // "Low", "Medium", "High", "Critical"
}

/// Dual-Plane Triage Dossier
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct TriageDossier {
    /// Plane A: Deterministic facts verified by schema and typed extractors
    pub deterministic_metrics: DeterministicMetrics,
    /// Plane B: Cognitive reasoning generated by meta-level agent
    pub cognitive_advisory: CognitiveAdvisory,

    // Legacy fields maintained for backward-compatibility with downstream clients
    pub intent_summary: String,
    pub blast_radius: BlastRadius,
    pub risk_factors: Vec<String>,
    pub mitigation_notes: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct CandidatePolicyRule {
    pub name: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_names: Option<Vec<String>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub operation_kind: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub min_amount_cents: Option<u64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub min_auth_level: Option<u8>,
    pub action: String, // STRICT INVARIANT: Must be "require_approval" or "deny" for synthetic rules
    pub priority: i32,
    pub justification: String,

    // Probationary Lifecycle & Guardrail Extensions
    #[serde(default)]
    pub lifecycle_state: RuleLifecycleState,
    #[serde(default = "default_probation_target")]
    pub probation_target: u32,
    #[serde(default)]
    pub confirmations_count: u32,
    #[serde(default = "default_quorum_approvers")]
    pub required_approver_quorum: u32,
    #[serde(default)]
    pub projected_fields: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub escalation_role: Option<String>,
}

fn default_probation_target() -> u32 {
    5
}

fn default_quorum_approvers() -> u32 {
    2
}

